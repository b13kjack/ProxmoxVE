#!/usr/bin/env bash
#
# Create the isolated vmbr1 NAT layout on the Proxmox host. Run as root:
#   bash setup-network.sh
#
# Layout (GUI-visible by design):
# - bridge stanza lives in /etc/network/interfaces, so Proxmox shows it and
#   a GUI edit cannot silently drop anything (no extra options live there).
# - NAT/FORWARD/DNAT rules live in the vmbr1-nat systemd oneshot unit, which
#   applies them at boot and on every re-run. Idempotent: safe to re-run.
#
# Result: vmbr1 (no physical ports, host holds $HOST_IP), MASQUERADE of
# $SUBNET out via $UPLINK, DNAT forwards for SSH/dashboard/(optional)
# gateway into the Hermes container (skipped with ROUTED=1).
# Every value can be overridden with env vars (see defaults below).

set -u

BRIDGE="${BRIDGE:-vmbr1}"
SUBNET="${SUBNET:-10.10.10.0/24}"
HOST_IP="${HOST_IP:-10.10.10.1}"
PREFIX="${PREFIX:-24}"
UPLINK="${UPLINK:-vmbr0}"
HERMES_IP="${HERMES_IP:-10.10.10.10}"
SSH_FWD_PORT="${SSH_FWD_PORT:-2222}"
DASHBOARD_FWD_PORT="${DASHBOARD_FWD_PORT:-9119}"
GATEWAY_FWD_PORT="${GATEWAY_FWD_PORT:-}"
# ROUTED=1: LAN reaches containers via a static route on the LAN router
# (10.10.10.0/24 via the Proxmox host) instead of DNAT forwards. Only
# MASQUERADE (internet) is installed; proxy targets are direct .10/.11 IPs.
ROUTED="${ROUTED:-0}"
# DASHBOARD_DNAT=1: install the dashboard DNAT forward even in ROUTED mode.
# Gives clients without the static route a stable LAN endpoint at
# <proxmox-lan-ip>:9119 -> HERMES_IP:9119. App-layer password auth is still
# enforced by the dashboard itself; DNAT only changes reachability.
DASHBOARD_DNAT="${DASHBOARD_DNAT:-0}"

APPLY_SCRIPT="/usr/local/sbin/${BRIDGE}-nat-apply"
UNIT="vmbr1-nat.service"
LEGACY_STANZA="/etc/network/interfaces.d/${BRIDGE}"

if [[ "$(id -u)" -ne 0 ]]; then
  echo "Run as root on the Proxmox host." >&2
  exit 1
fi

echo "== forwarding"
if [[ "$(cat /proc/sys/net/ipv4/ip_forward 2>/dev/null)" != "1" ]]; then
  sysctl -w net.ipv4.ip_forward=1
fi
echo "  [OK  ] IPv4 forwarding on"

echo "== bridge ${BRIDGE} (GUI-visible stanza)"
if [[ -f "$LEGACY_STANZA" ]]; then
  cp -a "$LEGACY_STANZA" "${LEGACY_STANZA}.bak-$(date +%F)" 2>/dev/null || true
  rm -f "$LEGACY_STANZA"
  echo "  [MIGR] legacy $LEGACY_STANZA backed up and removed (stanza moves to main file)"
fi
if grep -q "^iface ${BRIDGE} " /etc/network/interfaces 2>/dev/null; then
  echo "  [KEEP] stanza already in /etc/network/interfaces"
else
  cat >>/etc/network/interfaces <<EOF

auto ${BRIDGE}
iface ${BRIDGE} inet static
    address ${HOST_IP}/${PREFIX}
    bridge-ports none
    bridge-stp off
    bridge-fd 0
EOF
  echo "  [ADD ] stanza appended to /etc/network/interfaces"
fi
if ip link show "$BRIDGE" >/dev/null 2>&1; then
  echo "  [KEEP] bridge $BRIDGE up"
else
  ifup "$BRIDGE"
  echo "  [ADD ] bridge $BRIDGE brought up"
fi
if command -v bridge >/dev/null 2>&1 && bridge link show 2>/dev/null | grep -q "master ${BRIDGE}"; then
  echo "  [WARN] bridge $BRIDGE has enslaved ports; remove them to keep it isolated" >&2
fi

echo "== NAT rules (${UNIT})"
{
  echo "#!/usr/bin/env bash"
  echo "# Generated by debug/setup-network.sh - do not edit; re-run it instead."
  echo "set -u"
  echo 'ACTION="${1:-up}"'
  echo 'rule() {'
  echo '  local table="$1"; shift'
  echo '  if [[ "$ACTION" == "up" ]]; then'
  echo '    iptables -t "$table" -C "$@" 2>/dev/null || iptables -t "$table" -A "$@"'
  echo '  else'
  echo '    iptables -t "$table" -D "$@" 2>/dev/null || true'
  echo '  fi'
  echo '}'
  echo "rule nat POSTROUTING -s '${SUBNET}' -o ${UPLINK} -j MASQUERADE"
  echo "rule filter FORWARD -i ${UPLINK} -o ${BRIDGE} -d '${SUBNET}' -j ACCEPT"
  echo "rule filter FORWARD -i ${BRIDGE} -s '${SUBNET}' -o ${UPLINK} -j ACCEPT"
  if [[ "$ROUTED" != "1" ]]; then
    echo "rule nat PREROUTING -i ${UPLINK} -p tcp --dport ${SSH_FWD_PORT} -j DNAT --to-destination ${HERMES_IP}:22"
    echo "rule nat PREROUTING -i ${UPLINK} -p tcp --dport ${DASHBOARD_FWD_PORT} -j DNAT --to-destination ${HERMES_IP}:9119"
  elif [[ "$DASHBOARD_DNAT" == "1" ]]; then
    echo "rule nat PREROUTING -i ${UPLINK} -p tcp --dport ${DASHBOARD_FWD_PORT} -j DNAT --to-destination ${HERMES_IP}:9119"
  fi
  if [[ -n "$GATEWAY_FWD_PORT" ]]; then
    echo "rule nat PREROUTING -i ${UPLINK} -p tcp --dport ${GATEWAY_FWD_PORT} -j DNAT --to-destination ${HERMES_IP}:${GATEWAY_FWD_PORT}"
  fi
} >"$APPLY_SCRIPT"
chmod 750 "$APPLY_SCRIPT"
echo "  [WRIT] $APPLY_SCRIPT"

cat >/etc/systemd/system/$UNIT <<EOF
[Unit]
Description=${BRIDGE} NAT and forwards for isolated containers
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=${APPLY_SCRIPT} up
ExecStop=${APPLY_SCRIPT} down

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable -q "$UNIT"
systemctl restart "$UNIT"
echo "  [OK  ] $UNIT enabled and applied"

echo
echo "done. Containers: vmbr1, 10.10.10.x/24, gateway ${HOST_IP}."
if [[ "$ROUTED" == "1" ]]; then
  echo "ROUTED mode: add this static route on your LAN router:"
  echo "  10.10.10.0/24 via <proxmox-lan-ip>"
  echo "Then from LAN, reach containers directly:"
  echo "  SSH:      ssh root@${HERMES_IP} (port 22, no forward needed)"
  echo "  Dashboard reverse-proxy target: http://${HERMES_IP}:9119"
  echo "(If the datacenter firewall is enabled, allow FORWARD ${UPLINK}<->${BRIDGE} there too.)"
else
  echo "SSH:      <proxmox-lan-ip>:${SSH_FWD_PORT} -> ${HERMES_IP}:22"
  echo "Dashboard reverse-proxy target: http://<proxmox-lan-ip>:${DASHBOARD_FWD_PORT}"
fi
